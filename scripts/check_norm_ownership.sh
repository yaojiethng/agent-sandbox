#!/usr/bin/env bash
# scripts/check_norm_ownership.sh
# The norm-ownership ledger and its gate: every prose line in the two prose
# standards carries a kind and, where the kind is a rule, the observer that
# detects a violation of it.
#
# A norm is a rule when an observer catches its violation. An observer is a
# gate in scripts/lint.sh, a lint rule under scripts/lint/, or a maintenance
# skill a prompt dispatches. A norm with no observer is a judgement: it states
# how a writer decides, and it cannot be enforced because nothing detects a
# breach.
#
# Usage:
#   check_norm_ownership.sh --generate   rewrite the ledger from the sources,
#                                       preserving the kind and observer already
#                                       recorded for a line whose text is
#                                       unchanged, and marking a new line
#                                       UNCLASSIFIED
#   check_norm_ownership.sh --check      fail when a source line is unclassified,
#                                       a ledger row no longer exists, a kind is
#                                       outside the vocabulary, or an observer
#                                       names nothing that runs
#
# The ledger is `scripts/lint/norm-ownership.tsv`, five tab-separated columns:
# hash, source, kind, observer, text. The hash is the line's SHA-1, so an edited
# sentence loses its row and fails the gate until a reader classifies it again.

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LEDGER="$REPO_ROOT/scripts/lint/norm-ownership.tsv"
SOURCES=(
  "docs/policies/documentation_policy.md"
  "docs/development/prompt-authoring-conventions.md"
)

usage() { echo "usage: check_norm_ownership.sh [--generate|--check]" >&2; exit 2; }

# candidate_lines FILE  --  print every prose line of FILE, one per output line:
# non-blank, not a heading, not a frontmatter or rule line, not a table row, and
# not inside a fenced block. Each printed line is one census unit.
candidate_lines() {
  local file="$1"
  awk '
    /^```/ { fence = !fence; next }
    fence { next }
    /^---$/ { next }
    /^[[:space:]]*$/ { next }
    /^#/ { next }
    /^\|/ { next }
    { print }
  ' "$REPO_ROOT/$file"
}

# line_hash TEXT  --  the SHA-1 of the line, used as the ledger key so an edit
# to the sentence retires the old row and demands a new classification.
line_hash() { printf '%s' "$1" | sha1sum | cut -d' ' -f1; }

# observer_known OBSERVER  --  succeed when the observer names something that
# runs: a gate in the umbrella, a lint rule file, a maintenance skill, or a
# correction procedure prompt.
observer_known() {
  local obs="$1" name
  case "$obs" in
    none) return 0 ;;
    gate:*) name="${obs#gate:}"
            grep -qF -- "$name" "$REPO_ROOT/scripts/lint.sh" && return 0
            return 1 ;;
    lint:*) name="${obs#lint:}"
            [[ -f "$REPO_ROOT/scripts/lint/$name" ]] && return 0
            return 1 ;;
    review:*) name="${obs#review:}"
            [[ -d "$REPO_ROOT/workflow/coding-agent/skills/$name" ]] && return 0
            [[ -d "$REPO_ROOT/.agents/skills/$name" ]] && return 0
            return 1 ;;
    prompt:*) name="${obs#prompt:}"
            [[ -f "$REPO_ROOT/workflow/coding-agent/prompts/$name.md" ]] && return 0
            return 1 ;;
    *) return 1 ;;
  esac
}

generate() {
  local tmp file text hash kind obs
  tmp="$(mktemp)"
  {
    echo "# Norm-ownership ledger. Generated by scripts/check_norm_ownership.sh --generate."
    echo "# Columns: hash, source, kind, observer, text. Unit: one prose line."
    echo "# kind is rule, judgement or description, per docs/reference/agent_workflow.md ### Norm kinds. UNCLASSIFIED fails --check."
    echo "# observer is none, gate:<script>, lint:<file>, review:<skill> or prompt:<name>."
  } > "$tmp"
  for file in "${SOURCES[@]}"; do
    while IFS= read -r text; do
      hash="$(line_hash "$text")"
      kind="UNCLASSIFIED"; obs="UNCLASSIFIED"
      if [[ -f "$LEDGER" ]]; then
        local prior
        prior="$(awk -F'\t' -v h="$hash" '$1==h {print $3"\t"$4; exit}' "$LEDGER")"
        if [[ -n "$prior" ]]; then
          kind="${prior%%$'\t'*}"
          obs="${prior#*$'\t'}"
        fi
      fi
      printf '%s\t%s\t%s\t%s\t%s\n' "$hash" "$file" "$kind" "$obs" "$text" >> "$tmp"
    done < <(candidate_lines "$file")
  done
  mv "$tmp" "$LEDGER"
  echo "norm-ownership: wrote $(( $(wc -l < "$LEDGER") - 4 )) row(s) to ${LEDGER#"$REPO_ROOT"/}"
}

kinds_from_reference() {
  awk '/^### Norm kinds/{f=1; next} f && (/^## / || /^### /) {exit} f && /^\|/ && $0 !~ /^\| *Kind/ && $0 !~ /^\|---/ {gsub(/^\| */, ""); gsub(/ *\|.*/, ""); print}' \
    "$REPO_ROOT/docs/reference/agent_workflow.md"
}

check() {
  [[ -f "$LEDGER" ]] || { echo "norm-ownership: missing ledger $LEDGER" >&2; return 1; }
  local rc=0 file text hash kind obs count=0 gated=0 reviewed=0 judge=0 description=0
  local KINDS
  KINDS="$(kinds_from_reference | paste -sd'|' -)"
  if [[ -z "$KINDS" ]]; then
    echo "norm-ownership: no kind rows in docs/reference/agent_workflow.md ### Norm kinds" >&2
    return 1
  fi
  local -A seen=()
  while IFS= read -r row; do
    [[ "$row" == \#* || -z "$row" ]] && continue
    IFS=$'\t' read -r hash file kind obs text <<< "$row"
    seen["$hash"]=1
    count=$((count + 1))
    if ! printf '%s' "$KINDS" | tr '|' '\n' | grep -qx -- "$kind"; then
      echo "norm-ownership: $file has kind '$kind', which the reference table does not state, for: ${text:0:70}..." >&2
      rc=1
      continue
    fi
    if ! observer_known "$obs"; then
      echo "norm-ownership: $file names observer '$obs' that does not run, for: ${text:0:70}..." >&2
      rc=1
      continue
    fi
    case "$kind-$obs" in
      rule-gate:*) gated=$((gated + 1)) ;;
      rule-lint:*) gated=$((gated + 1)) ;;
      rule-review:*) reviewed=$((reviewed + 1)) ;;
      rule-prompt:*) reviewed=$((reviewed + 1)) ;;
      judgement-none) judge=$((judge + 1)) ;;
      description-none) description=$((description + 1)) ;;
      description-*)
        echo "norm-ownership: $file marks a description with an observer '$obs', for: ${text:0:70}..." >&2
        rc=1 ;;
      judgement-*)
        echo "norm-ownership: $file marks a judgement with an observer '$obs', for: ${text:0:70}..." >&2
        rc=1 ;;
      *-none)
        echo "norm-ownership: $file marks a rule with no observer, for: ${text:0:70}..." >&2
        rc=1 ;;
      *) gated=$((gated + 1)) ;;
    esac
  done < "$LEDGER"
  for file in "${SOURCES[@]}"; do
    while IFS= read -r text; do
      hash="$(line_hash "$text")"
      if [[ -z "${seen[$hash]:-}" ]]; then
        echo "norm-ownership: $file has an unclassified line: ${text:0:70}..." >&2
        rc=1
      fi
    done < <(candidate_lines "$file")
  done
  # A ledger row whose sentence left its source is an orphan: either the sentence
  # was deleted and its rule needs re-homing, or the plan drifted from the text.
  while IFS= read -r row; do
    [[ "$row" == \#* || -z "$row" ]] && continue
    IFS=$'\t' read -r hash file kind obs text <<< "$row"
    if [[ ! -f "$REPO_ROOT/$file" ]] || ! grep -Fxq -- "$text" "$REPO_ROOT/$file"; then
      echo "norm-ownership: orphaned row for $file: ${text:0:70}..." >&2
      rc=1
    fi
  done < "$LEDGER"
  if [[ $rc -eq 0 ]]; then
    echo "norm-ownership: clean across $count row(s), $gated gated, $reviewed reviewed, $judge judgement, $description description"
  fi
  return $rc
}

case "${1:---check}" in
  --generate) generate ;;
  --check) check ;;
  *) usage ;;
esac
